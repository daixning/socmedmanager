// Stable signing: updates only install over an existing install when signed with the SAME key.
// Release key: keystore.properties (storeFile, storePassword, keyAlias, keyPassword) or the
// SIGNING_* environment variables used by CI. If neither is present the committed app/debug.keystore
// is used so every build from this repo is still signed with one consistent key.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun signingValue(prop: String, env: String): String? = keystoreProps.getProperty(prop) ?: System.getenv(env)

